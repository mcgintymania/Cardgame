// Generates supabase/migrations/..._seed.sql from the game's own data, so the
// database catalogue and club always match the app. Run: bun scripts/gen-seed.ts
import { writeFileSync } from 'fs';
import { CATALOGUE } from '../apps/web/src/lib/catalogue.ts';
import { GAMES, ROSTER, playsGame } from '../apps/web/src/lib/roster.ts';
import { startingRating } from '../apps/web/src/lib/club.ts';

const q = (s: string | null | undefined) => (s === null || s === undefined ? 'null' : `'${s.replace(/'/g, "''")}'`);
const j = (o: unknown) => `${q(JSON.stringify(o))}::jsonb`;
const out: string[] = [];
out.push(`-- CARD CLUB — seed data (migration 2 of 2). GENERATED by scripts/gen-seed.ts: don't edit by hand.
-- Safe to run again: everything is an upsert.
`);

out.push('-- The catalogue');
out.push('insert into public.cosmetic_items (id, name, slot, kind, rarity, unlock, season, data) values');
out.push(CATALOGUE.map((i) => `  (${q(i.id)}, ${q(i.name)}, ${q(i.slot)}, ${q(i.kind)}, ${q(i.rarity)}, ${j(i.unlock)}, ${q(i.season ?? null)}, ${j({ c1: i.c1, c2: i.c2, c3: i.c3, desc: i.desc })})`).join(',\n'));
out.push('on conflict (id) do update set name = excluded.name, slot = excluded.slot, kind = excluded.kind, rarity = excluded.rarity, unlock = excluded.unlock, season = excluded.season, data = excluded.data;\n');

out.push('-- The 25 AI members');
out.push('insert into public.club_members (kind, ai_key, name, style, skills, tagline) values');
out.push(ROSTER.map((c) => `  ('ai', ${q(c.id)}, ${q(c.name)}, ${q(c.style)}, ${j(c.skill)}, ${q(c.tagline)})`).join(',\n'));
out.push('on conflict (ai_key) do update set name = excluded.name, style = excluded.style, skills = excluded.skills, tagline = excluded.tagline;\n');

out.push('-- Starting ratings for the games each member plays');
const rows: string[] = [];
for (const c of ROSTER) for (const g of GAMES) if (playsGame(c, g)) {
  const r = startingRating(c.skill[g]);
  rows.push(`  ((select id from public.club_members where ai_key = ${q(c.id)}), ${q(g)}, ${r}, ${r})`);
}
out.push('insert into public.ratings (member_id, game, rating, peak) values');
out.push(rows.join(',\n'));
out.push('on conflict (member_id, game) do nothing;\n');

out.push('-- First champions: the strongest member at each game');
for (const g of GAMES) {
  const champ = ROSTER.filter((c) => playsGame(c, g)).sort((a, b) => b.skill[g] - a.skill[g])[0];
  out.push(`insert into public.titles (game, holder, defences) values (${q(g)}, (select id from public.club_members where ai_key = ${q(champ.id)}), 0) on conflict (game) do nothing;`);
  out.push(`insert into public.title_reigns (game, holder, won_at, defences) select ${q(g)}, holder, won_at, 0 from public.titles where game = ${q(g)} and not exists (select 1 from public.title_reigns where game = ${q(g)});`);
}
out.push(`\ninsert into public.club_news (kind, text) select 'club', 'The club is open. Win matches to climb the rankings and earn a title shot.' where not exists (select 1 from public.club_news);`);

writeFileSync('supabase/migrations/20261031000002_seed.sql', out.join('\n') + '\n');
console.log(`items ${CATALOGUE.length}, members ${ROSTER.length}, ratings ${rows.length}`);
