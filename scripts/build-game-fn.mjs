// Bundles the "game" Edge Function (server + the whole rules engine) into ONE
// file, supabase/functions/game/index.ts, ready to paste into the Supabase editor.
import { build } from 'esbuild';
import { writeFileSync } from 'fs';
const r = await build({
  entryPoints: ['supabase/functions/game/src/main.ts'], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
  external: ['npm:*'], write: false, minify: true, legalComments: 'none', logLevel: 'warning',
});
const banner = `// @ts-nocheck\n// Card Club — "game" Edge Function. GENERATED by scripts/build-game-fn.mjs from supabase/functions/game/src.\n// Paste this whole file into the Supabase editor as the function "game". Don't edit it by hand.\n`;
writeFileSync('supabase/functions/game/index.ts', banner + r.outputFiles[0].text);
console.log('supabase/functions/game/index.ts', (r.outputFiles[0].text.length / 1024).toFixed(0), 'KB');
